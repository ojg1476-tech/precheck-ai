# ── 중복 제거·split·저장 ─────────────────────────────────
seen, uniq = set(), []
for r in rows:
    k = (r["product_type"], r["text"])
    if k not in seen:
        seen.add(k)
        uniq.append(r)
rng = random.Random(20261026)
groups = {}
for r in uniq:
    groups.setdefault((r["label"], r["product_type"][:1]), []).append(r)
for g in groups.values():
    rng.shuffle(g)
    for i, r in enumerate(g):
        r["split"] = "dev" if i % 2 == 0 else "test"
for i, r in enumerate(uniq, 1):
    r["id"] = f"E{i:03d}"
out = Path(__file__).resolve().parent.parent / "data" / "eval_set.csv"
with open(out, "w", encoding="utf-8", newline="") as f:
    w = csv.DictWriter(f, fieldnames=["id", "split", "product_type", "label", "category", "text", "source", "source_url"])
    w.writeheader()
    w.writerows(uniq)
print(len(uniq), "rows →", out)
